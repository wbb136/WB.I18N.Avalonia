using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace WB.I18N.Avalonia.Tests.Generator;

/// <summary>验证三种资源声明写法、生成入口及已有程序集标记的兼容性。</summary>
public sealed class ResourceDeclarationTests
{
    private const string GreetingResource = """<root><data name="Greeting"><value>Hello</value></data></root>""";

    /// <summary>字符串资源位置生成完整公开 API 和对应资源键。</summary>
    [Fact]
    public void GeneratesPublicApiForStringResource()
    {
        var resource = new InMemoryAdditionalText(GeneratorHarness.ResourcePath, GreetingResource, GeneratorHarness.BaseName);
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(GeneratorHarness.NormalDeclaration);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(resource);

        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation updated, out _);
        GeneratorRunResult result = Assert.Single(driver.GetRunResult().Results);

        Assert.Empty(result.Diagnostics);
        Assert.DoesNotContain(updated.GetDiagnostics(), IsError);
        Assert.Equal(2, result.GeneratedSources.Length);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            [assembly: global::WB.I18N.Avalonia.I18NResourceAttribute("TestProject.Messages")]

            namespace TestProject;

            public static partial class I18N
            {
                /// <summary>在程序集初始化时注册该程序集声明的语言资源。</summary>
                [global::System.Runtime.CompilerServices.ModuleInitializerAttribute]
                internal static void RegisterI18NResources()
                {
                    global::WB.I18N.Avalonia.I18NExtension.RegisterResourceAssembly(typeof(I18N).Assembly);
                }

                /// <summary>获取当前应用共享的语言状态。</summary>
                public static global::WB.I18N.Avalonia.I18NExtension Current
                {
                    get
                    {
                        return global::WB.I18N.Avalonia.I18NExtension.Current;
                    }
                }

                /// <summary>查找当前语言的资源文案。</summary>
                public static string GetString(string? resourceKey, string? fallback = null)
                {
                    return global::WB.I18N.Avalonia.I18NExtension.GetString(resourceKey, fallback);
                }

                /// <summary>查找并格式化当前语言的资源模板。</summary>
                public static string Format(string resourceKey, params object?[]? arguments)
                {
                    return global::WB.I18N.Avalonia.I18NExtension.Format(resourceKey, arguments);
                }
            }
            """.ReplaceLineEndings("\n"),
            GeneratorHarness.GetGeneratedSource(result, "I18N.g.cs").ReplaceLineEndings("\n"));
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            namespace TestProject;

            /// <summary>提供由默认资源生成的本地化键。</summary>
            public static class I18NKeys
            {
                /// <summary>获取用于查找对应翻译的资源键。</summary>
                public const string Greeting = "Greeting";
            }
            """.ReplaceLineEndings("\n") + "\n",
            GeneratorHarness.GetGeneratedSource(result, "I18NKeys.g.cs").ReplaceLineEndings("\n"));
    }

    /// <summary>类型资源位置使用资源类型的完整名称并保持声明的可见性。</summary>
    [Fact]
    public void GeneratesKeysForTypeResource()
    {
        const string source = """
            using WB.I18N.Avalonia;

            namespace TestProject;

            public sealed class Messages
            {
            }

            [I18NResource(typeof(Messages))]
            internal static partial class I18N
            {
            }
            """;
        var resource = new InMemoryAdditionalText(GeneratorHarness.ResourcePath, GreetingResource, GeneratorHarness.BaseName);
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(source);
        GeneratorDriver driver = GeneratorHarness.CreateDriver(resource);

        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation updated, out _);
        GeneratorRunResult result = Assert.Single(driver.GetRunResult().Results);

        Assert.Empty(result.Diagnostics);
        Assert.DoesNotContain(updated.GetDiagnostics(), IsError);
        Assert.Contains(
            "[assembly: global::WB.I18N.Avalonia.I18NResourceAttribute(typeof(global::TestProject.Messages))]",
            GeneratorHarness.GetGeneratedSource(result, "I18N.g.cs"),
            StringComparison.Ordinal);
        INamedTypeSymbol keys = Assert.IsAssignableFrom<INamedTypeSymbol>(updated.GetTypeByMetadataName("TestProject.I18NKeys"));
        Assert.Equal(Accessibility.Internal, keys.DeclaredAccessibility);
        Assert.Equal("Greeting", Assert.IsAssignableFrom<IFieldSymbol>(Assert.Single(keys.GetMembers("Greeting"))).ConstantValue);
    }

    /// <summary>外部锚点和明确清单名只匹配外部资源程序集的中性资源。</summary>
    [Fact]
    public void GeneratesKeysForExternalAnchorResource()
    {
        const string anchorSource = """
            namespace Shared;

            public sealed class Anchor
            {
            }
            """;
        const string source = """
            using WB.I18N.Avalonia;

            namespace TestProject;

            [I18NResource(typeof(Shared.Anchor), "Shared.Text")]
            public static partial class I18N
            {
            }
            """;
        using (var stream = new MemoryStream())
        {
            Assert.True(GeneratorHarness.CreateCompilation(anchorSource, "SharedResources").Emit(stream).Success);
            MetadataReference anchor = MetadataReference.CreateFromImage(stream.ToArray());
            CSharpCompilation compilation = GeneratorHarness.CreateCompilation(source).AddReferences(anchor);
            var resource = new InMemoryAdditionalText(GeneratorHarness.ResourcePath, GreetingResource, "Shared.Text", "sharedresources");
            var localResource = new InMemoryAdditionalText(
                "/src/Local.resx",
                """<root><data name="LocalOnly"><value>本地</value></data></root>""",
                "Shared.Text",
                GeneratorHarness.ProjectName);
            GeneratorDriver driver = GeneratorHarness.CreateDriver(resource, localResource);

            driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation updated, out _);
            GeneratorRunResult result = Assert.Single(driver.GetRunResult().Results);

            Assert.Empty(result.Diagnostics);
            Assert.DoesNotContain(updated.GetDiagnostics(), IsError);
            Assert.Contains(
                """[assembly: global::WB.I18N.Avalonia.I18NResourceAttribute(typeof(global::Shared.Anchor), "Shared.Text")]""",
                GeneratorHarness.GetGeneratedSource(result, "I18N.g.cs"),
                StringComparison.Ordinal);
            INamedTypeSymbol keys = Assert.IsAssignableFrom<INamedTypeSymbol>(updated.GetTypeByMetadataName("TestProject.I18NKeys"));
            Assert.Single(keys.GetMembers("Greeting"));
            Assert.Empty(keys.GetMembers("LocalOnly"));
        }
    }

    /// <summary>已有匹配程序集标记时只生成访问入口，不重复生成程序集标记。</summary>
    [Fact]
    public void PreservesExistingMatchingAssemblyRegistration()
    {
        const string registration = """
            [assembly: WB.I18N.Avalonia.I18NResource("TestProject.Messages")]
            """;
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(GeneratorHarness.NormalDeclaration)
            .AddSyntaxTrees(GeneratorHarness.CreateSyntaxTree(registration, "/src/AssemblyInfo.cs"));
        GeneratorDriver driver = GeneratorHarness.CreateDriver();

        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation updated, out _);
        GeneratorRunResult result = Assert.Single(driver.GetRunResult().Results);

        Assert.Empty(result.Diagnostics);
        Assert.DoesNotContain(updated.GetDiagnostics(), IsError);
        Assert.Single(result.GeneratedSources);
        Assert.DoesNotContain(
            "[assembly:",
            GeneratorHarness.GetGeneratedSource(result, "I18N.g.cs"),
            StringComparison.Ordinal);
    }

    /// <summary>仅声明程序集资源时由运行时处理，不创建新的访问入口。</summary>
    [Fact]
    public void DoesNotGenerateApiForAssemblyOnlyRegistration()
    {
        const string source = """
            [assembly: WB.I18N.Avalonia.I18NResource("TestProject.Messages")]
            """;
        CSharpCompilation compilation = GeneratorHarness.CreateCompilation(source);
        GeneratorDriver driver = GeneratorHarness.CreateDriver();

        driver = driver.RunGenerators(compilation);
        GeneratorRunResult result = Assert.Single(driver.GetRunResult().Results);

        Assert.Empty(result.Diagnostics);
        Assert.Empty(result.GeneratedSources);
    }

    /// <summary>忽略不影响内存编译的 Roslyn 信息和警告。</summary>
    private static bool IsError(Diagnostic diagnostic)
    {
        return diagnostic.Severity == DiagnosticSeverity.Error;
    }
}
