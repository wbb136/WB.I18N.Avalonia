using System;
using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace WB.I18N.Generator;

/// <summary>把默认资源键生成可供 C# 和 AXAML 引用的字符串常量。</summary>
internal static class ResourceKeyEmitter
{
    /// <summary>按资源键顺序生成类型，保留原始键值并为非法或重复标识符分配稳定名称。</summary>
    public static string CreateSource(
        string typeName,
        string accessibility,
        string namespaceDeclaration,
        IEnumerable<string> keys
    )
    {
        var orderedKeys = new SortedSet<string>(keys, StringComparer.Ordinal);
        var usedNames = new HashSet<string>(StringComparer.Ordinal) { typeName };
        var identifiers = new Dictionary<string, string>(StringComparer.Ordinal);

        // 预留本身已是合法标识符的键，避免特殊字符替换后占用正常键名。
        foreach (string key in orderedKeys)
        {
            string identifier = ToIdentifier(key);
            if (key == identifier && usedNames.Add(identifier))
            {
                identifiers.Add(key, identifier);
            }
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        if (namespaceDeclaration.Length != 0)
        {
            source.AppendLine(namespaceDeclaration);
            source.AppendLine();
        }

        source.AppendLine("/// <summary>提供由默认资源生成的本地化键。</summary>");
        source.Append(accessibility).Append(" static class ").AppendLine(typeName);
        source.AppendLine("{");
        foreach (string key in orderedKeys)
        {
            if (!identifiers.TryGetValue(key, out string? identifier))
            {
                string candidate = ToIdentifier(key);
                identifier = candidate;
                int suffix = 2;
                while (!usedNames.Add(identifier))
                {
                    identifier = candidate + "_" + suffix.ToString(System.Globalization.CultureInfo.InvariantCulture);
                    suffix++;
                }
            }

            source.AppendLine("    /// <summary>获取用于查找对应翻译的资源键。</summary>");
            source.Append("    public const string ").Append(identifier).Append(" = ")
                .Append(SymbolDisplay.FormatLiteral(key, quote: true)).AppendLine(";");
        }

        source.AppendLine("}");
        return source.ToString();
    }

    /// <summary>将不能用于 C# 标识符的字符替换为下划线，并处理数字开头及保留字。</summary>
    private static string ToIdentifier(string key)
    {
        var identifier = new StringBuilder(key.Length + 1);
        if (!SyntaxFacts.IsIdentifierStartCharacter(key[0]) && SyntaxFacts.IsIdentifierPartCharacter(key[0]))
        {
            identifier.Append('_');
        }

        foreach (char character in key)
        {
            // 格式字符会被 C# 编译器忽略，替换成下划线后才能检查真实的命名冲突。
            if (SyntaxFacts.IsIdentifierPartCharacter(character) &&
                char.GetUnicodeCategory(character) != System.Globalization.UnicodeCategory.Format)
            {
                identifier.Append(character);
            }
            else
            {
                identifier.Append('_');
            }
        }

        string result = identifier.ToString();
        if (SyntaxFacts.GetKeywordKind(result) != SyntaxKind.None)
        {
            return "_" + result;
        }

        return result;
    }
}
